// Generates client recovery-window constants from the daemon's policy.
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/Lewin671/remote-agent/internal/deviceauth"
)

func generated(language string) string {
	ms := deviceauth.ResultRetention.Milliseconds()
	switch language {
	case "typescript":
		return fmt.Sprintf("// Code generated by go generate ./internal/deviceauth; DO NOT EDIT.\nexport const RESULT_RETENTION_MS = %d;\n", ms)
	case "kotlin":
		return fmt.Sprintf("// Code generated by scripts/gen-result-retention -language kotlin; DO NOT EDIT.\npackage io.github.lewin671.remoteagent.core\n\ninternal const val RESULT_RETENTION_MS: Long = %dL\n", ms)
	case "swift":
		return fmt.Sprintf("// Code generated by scripts/gen-result-retention -language swift; DO NOT EDIT.\nlet resultRetentionMs: Int64 = %d\n", ms)
	default:
		panic("unsupported output language")
	}
}

func main() {
	output := flag.String("output", "", "generated destination")
	language := flag.String("language", "typescript", "typescript, kotlin or swift")
	flag.Parse()
	source := generated(*language)
	if *output == "" {
		fmt.Print(source)
		return
	}
	if err := os.WriteFile(*output, []byte(source), 0644); err != nil {
		panic(err)
	}
}
