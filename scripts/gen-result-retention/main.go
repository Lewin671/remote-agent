// Generates the web recovery-window constant from the daemon's policy.
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/Lewin671/remote-agent/internal/deviceauth"
)

func main() {
	output := flag.String("output", "", "generated TypeScript destination")
	flag.Parse()
	source := fmt.Sprintf("// Code generated by go generate ./internal/deviceauth; DO NOT EDIT.\nexport const RESULT_RETENTION_MS = %d;\n", deviceauth.ResultRetention.Milliseconds())
	if *output == "" {
		fmt.Print(source)
		return
	}
	if err := os.WriteFile(*output, []byte(source), 0644); err != nil {
		panic(err)
	}
}
