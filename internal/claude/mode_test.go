// Captured on Claude Code 2.1.300 in an isolated tmux session. A completed
// turn can leave a live Bash shell; this is a safety refusal, not a failure
// to parse the mode. Once the shell finishes, the same switch succeeds.
func TestSetModeWithCapturedBackgroundShell(t *testing.T) {
	synctest.Test(t, func(t *testing.T) {
		a, _ := testAdapter(t)
		f := &capturedModeClaude{fakeClaude: &fakeClaude{noBypass: true}}
		f.mode = index("plan")
		for _, name := range []string{"background-shell", "finished-shell"} {
			b, err := os.ReadFile("testdata/mode/" + name + "-2.1.300.txt")
			if err != nil {
				t.Fatal(err)
			}
			f.capture = string(b)
			scr := AnalyzeScreen(f.capture)
			if !scr.ComposerReady || !scr.DraftEmpty || scr.Busy || scr.Mode != "plan" {
				t.Fatalf("%s: %+v", name, scr)
			}
			err = a.SetMode(f, pb.ApprovalMode_APPROVAL_MODE_ASK, false, agent.ModeFacts{Model: "claude-haiku-5-5"})
			if name == "background-shell" {
				if !errors.Is(err, agent.ErrBackground) || len(f.writes) != 0 || BackgroundWork(f.capture) != "1 shell" {
					t.Fatalf("live shell: %v, writes %q", err, f.writes)
				}
			} else if err != nil || cycle[f.mode] != "default" || BackgroundWork(f.capture) != "" {
				t.Fatalf("finished shell: %v, mode %s", err, cycle[f.mode])
			}
		}
	})
}

type capturedModeClaude struct {
	*fakeClaude
	capture string
}

func (f *capturedModeClaude) Capture() (string, error) {
	return strings.Replace(f.capture, "⏸ plan mode on", strings.TrimSuffix(f.modeLine(), " (shift+tab to cycle)"), 1), nil
}

// Current evidence that auto is not on offer wins over having seen it
// with another model (review verify3 P2).
func TestAutoSeenWithAnotherModel(t *testing.T) {
	synctest.Test(t, testAutoSeenWithAnotherModel)
}

func testAutoSeenWithAnotherModel(t *testing.T) {
	cat := testCatalog(t)
	if o := offered(cat, agent.ModeFacts{Seen: []string{"auto"}, Model: "claude-haiku-4-5-20251001"}); o["auto"] {
		t.Fatal("haiku now, auto seen before")
	}
	a, _ := testAdapter(t)
	f := &fakeClaude{noAuto: true}
	f.mode = index("plan")
	err := a.SetMode(f, pb.ApprovalMode_APPROVAL_MODE_ASK, false, agent.ModeFacts{FullAccess: true, Model: "claude-haiku-4-5-20251001", Seen: []string{"auto"}})
	if err != nil || cycle[f.mode] != "default" || strings.Join(f.writes, "|") != strings.Repeat(agent.KeyBTab, 2) {
		t.Fatalf("plan → ask: %v %q %s", err, f.writes, cycle[f.mode])
	}
}

// A /model typed in the terminal is in the transcript as the command's
// output (records as 2.1.284 writes them). The replies of a Plan turn name
// Plan mode's model and are skipped, so without reading that record the
// session would still count as haiku, auto as not on offer, and a running
// Plan → ask, which then passes auto, as safe.
func TestModelSwitchedInTerminal(t *testing.T) {
	synctest.Test(t, testModelSwitchedInTerminal)
}

func testModelSwitchedInTerminal(t *testing.T) {
	p := NewParser()
	p.catalog = testCatalog(t)
	var ctx *pb.TurnContext
	feed := func(lines ...string) {
		t.Helper()
		for _, l := range lines {
			evs, err := p.Parse([]byte(l))
			if err != nil {
				t.Fatal(err)
			}
			for _, e := range evs {
				if c := e.GetTurnContext(); c != nil {
					ctx = c
				}
			}
		}
	}
	feed(
		`{"type":"user","promptId":"p1","origin":{"kind":"human"},"permissionMode":"default","message":{"role":"user","content":"hi"}}`,
		`{"type":"assistant","message":{"id":"m1","model":"claude-haiku-4-5-20251001","stop_reason":"end_turn","content":[{"type":"text","text":"x"}]},"perTurnEffort":null}`,
		`{"type":"system","subtype":"turn_duration","durationMs":1}`,
		`{"type":"user","isMeta":true,"message":{"role":"user","content":"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}}`,
		`{"type":"user","message":{"role":"user","content":"<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args></command-args>"}}`,
		"{\"type\":\"user\",\"message\":{\"role\":\"user\",\"content\":\"<local-command-stdout>Set model to `Sonnet 5.5` for this session only with `low` effort</local-command-stdout>\"}}",
	)
	if ctx == nil || ctx.Model != "claude-sonnet-5-5" || ctx.Effort != "low" || ctx.PermissionMode != "default" {
		t.Fatalf("context after /model: %v", ctx)
	}
	feed(
		`{"type":"user","promptId":"p2","origin":{"kind":"human"},"permissionMode":"plan","message":{"role":"user","content":"plan it"}}`,
		`{"type":"assistant","message":{"id":"m2","model":"claude-sonnet-5-5","content":[{"type":"tool_use","id":"t1","name":"Bash","input":{"command":"sleep 20"}}]},"perTurnEffort":"medium"}`,
	)
	if ctx.Model != "claude-sonnet-5-5" || ctx.Effort != "low" || ctx.PermissionMode != "plan" {
		t.Fatalf("context in the Plan turn: %v", ctx)
	}
	a, _ := testAdapter(t)
	f := &fakeClaude{noBypass: true}
	f.mode = index("plan")
	if err := a.SetMode(f, pb.ApprovalMode_APPROVAL_MODE_ASK, true, agent.ModeFacts{Model: ctx.Model}); !errors.Is(err, agent.ErrBusy) || len(f.writes) != 0 {
		t.Fatalf("running plan → ask via auto: %v %q", err, f.writes)
	}

	// The other ways Claude Code words it: an effort that did not change is
	// not named and stays; as the default; without the quotes of 2.1.284's
	// first builds; a model that is not in the catalog keeps its name.
	for _, c := range []struct{ out, model, effort string }{
		{"Set model to `Opus 5.5` for this session only", "claude-opus-5-5", "low"},
		{"Set model to `Fable 5.1` and saved as your default for new sessions", "claude-fable-5-1", "low"},
		{"Set model to `Opus 5.5 (1M context) (default)` and saved as your default for new sessions", "claude-opus-5-5", "low"},
		{"Set model to Sonnet 5.5 for this session only with high effort", "claude-sonnet-5-5", "high"},
		{"Set model to `Haiku 4.5` for this session only", "claude-haiku-4-5-20251001", ""},
		{"Set model to `Mythos 1` for this session only", "Mythos 1", ""},
	} {
		line, _ := json.Marshal(map[string]any{"type": "user", "message": map[string]any{"role": "user", "content": "<local-command-stdout>" + c.out + "</local-command-stdout>"}})
		feed(string(line))
		if ctx.Model != c.model || ctx.Effort != c.effort {
			t.Errorf("%s: context %v", c.out, ctx)
		}
	}
	// What a person typed is a message, whatever it says, and other output
	// changes nothing.
	before := ctx
	feed(
		"{\"type\":\"user\",\"promptId\":\"p3\",\"origin\":{\"kind\":\"human\"},\"permissionMode\":\"plan\",\"message\":{\"role\":\"user\",\"content\":\"<local-command-stdout>Set model to `Haiku 4.5` for this session only</local-command-stdout>\"}}",
		`{"type":"user","message":{"role":"user","content":"<local-command-stdout>Enabled plan mode</local-command-stdout>"}}`,
	)
	if ctx != before {
		t.Fatalf("context changed: %v", ctx)
	}
}

// Auto comes with the model, as the catalog says: Haiku 4.5 and older
// take none, the models after it do. A model the catalog does not know —
// an alias older settings name, or one from another CLI — gives no answer,
// and a running turn is not taken from Plan to ask through it.
func TestAutoOfModels(t *testing.T) {
	synctest.Test(t, testAutoOfModels)
}

func testAutoOfModels(t *testing.T) {
	cat := testCatalog(t)
	for model, want := range map[string]string{
		"claude-haiku-4-5-20251001": "off", "claude-3-5-haiku-20241022": "unknown",
		"claude-haiku-5-5": "on", "claude-sonnet-5-5": "on", "haiku": "unknown", "": "unknown",
	} {
		got := "unknown"
		if on, known := offered(cat, agent.ModeFacts{Model: model})["auto"]; known {
			got = map[bool]string{true: "on", false: "off"}[on]
		}
		if got != want {
			t.Errorf("%q: auto %s, want %s", model, got, want)
		}
	}
	a, _ := testAdapter(t)
	for _, model := range []string{"haiku", "claude-haiku-5-5", "claude-sonnet-5-5"} {
		f := &fakeClaude{noBypass: true}
		f.mode = index("plan")
		if err := a.SetMode(f, pb.ApprovalMode_APPROVAL_MODE_ASK, true, agent.ModeFacts{Model: model}); !errors.Is(err, agent.ErrBusy) || len(f.writes) != 0 {
			t.Errorf("%s, running plan → ask via auto: %v %q", model, err, f.writes)
		}
	}
	// Idle, the alias is taken through whichever way its model has.
	for _, noAuto := range []bool{true, false} {
		f := &fakeClaude{noBypass: true, noAuto: noAuto}
		f.mode = index("plan")
		if err := a.SetMode(f, pb.ApprovalMode_APPROVAL_MODE_ASK, false, agent.ModeFacts{Model: "haiku"}); err != nil || cycle[f.mode] != "default" {
			t.Errorf("idle plan → ask, auto on offer %v: %v, ends in %s", !noAuto, err, cycle[f.mode])
		}
	}
}
