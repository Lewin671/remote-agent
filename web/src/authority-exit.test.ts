import { createClient } from "@connectrpc/connect";
import { createConnectTransport } from "@connectrpc/connect-web";
import { afterEach, beforeAll, expect, it, vi } from "vitest";
import { AuthorityClient } from "./authority-client";
import { authorityServices } from "./authority-setup";
import { DeviceSecurityClient } from "./device-security-client";
import { loadSecurity, updateSecurityEntry } from "./device-security-store";
import { PairingService } from "./gen/remoteagent/v1/relay_pb";
import { AuthorityLifecycle, claimSecurityOperation, operation, readSecurityOperation, saveSecurityOperation } from "./security-operation";
import { securityFixture, storedSecurity } from "./test/stored-security-fixture";

let lifecycle: AuthorityLifecycle;
beforeAll(securityFixture);
afterEach(() => { lifecycle?.dispose(); vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.useRealTimers(); });

it("allows explicit exit from unsigned and uncertain signed offers but retains delivered offers and confirmed rotations", async () => {
  const f = await storedSecurity();
  vi.stubGlobal("navigator", { locks: { request: (_name: string, _options: object, work: () => Promise<unknown>) => work() } });
  lifecycle = new AuthorityLifecycle(() => true);
  const account = { server: "https://relay.example.com", deviceId: f.memberID, devicePrivate: f.ed };
  const unexpected = vi.fn(async () => { throw new Error("discard must stay local"); });
  vi.stubGlobal("fetch", unexpected);
  const services = authorityServices(account.server);
  const pairing = createClient(PairingService, createConnectTransport({ baseUrl: account.server }));
  const security = new DeviceSecurityClient(account.deviceId, account.devicePrivate, unexpected, () => true);
  const authority = new AuthorityClient(account, security, services.client("synthetic-token"), pairing, unexpected, lifecycle);
  const sign = vi.spyOn(crypto.subtle, "sign");
  const record = await loadSecurity();
  let op = operation("offer", account.server, account.deviceId, record.stateHash, { recoveryEd: new Uint8Array(32).fill(7) });
  await claimSecurityOperation(op, record.stateHash);
  op = await saveSecurityOperation(op, { ...op, codeSaved: true });
  await authority.discardUnpublishedCode();
  expect(await readSecurityOperation()).toBeUndefined();
  await claimSecurityOperation(op, record.stateHash);
  op = await saveSecurityOperation(op, { ...op, signed: new Uint8Array([1]) });
  await authority.discardUnpublishedCode();
  expect(await readSecurityOperation()).toBeUndefined();
  await claimSecurityOperation(op, record.stateHash);
  op = await saveSecurityOperation(op, { ...op, phase: "DELIVERED" });
  await expect(authority.discardUnpublishedCode()).rejects.toThrow();
  expect((await readSecurityOperation())!.signed).toEqual(new Uint8Array([1]));
  expect((await readSecurityOperation())!.phase).toBe("DELIVERED");
  await updateSecurityEntry("pending", () => undefined);
  const rotation = operation("state", account.server, account.deviceId, record.stateHash, { action: "recovery" });
  await claimSecurityOperation(rotation, record.stateHash);
  await saveSecurityOperation(rotation, { ...rotation, codeSaved: true });
  await expect(authority.discardUnpublishedCode()).rejects.toThrow();
  expect((await readSecurityOperation())!.codeSaved).toBe(true);
  expect(unexpected).not.toHaveBeenCalled();
  expect(sign).not.toHaveBeenCalled();
});
